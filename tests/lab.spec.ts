test('capture local RC animation performance without device-wide claims', async ({ page }, testInfo) => {
  await page.goto('/'); await tab(page, 1);
  await panel(page, 1).getByRole('button', { name: 'Charge', exact: true }).click();
  const measurement = await page.evaluate(async () => {
    const deltas: number[] = []; let longTasks = 0;
    const observer = new PerformanceObserver(list => { longTasks += list.getEntries().length; });
    observer.observe({ type: 'longtask', buffered: false });
    await new Promise<void>(resolve => { const start = performance.now(); let previous = start; const frame = (now: number) => { deltas.push(now - previous); previous = now; if (now - start < 1800) requestAnimationFrame(frame); else resolve(); }; requestAnimationFrame(frame); });
    observer.disconnect(); deltas.shift(); deltas.sort((a, b) => a - b);
    return { browser: navigator.userAgent, viewport: `${innerWidth}×${innerHeight}`, sampleFrames: deltas.length, medianFrameMs: deltas[Math.floor(deltas.length / 2)], p95FrameMs: deltas[Math.floor(deltas.length * .95)], longTasks, policy: '30 Hz UI commit cap; unthrottled headless Chromium on this workstation, not a phone benchmark.' };
  });
  await testInfo.attach('local-animation-performance', { body: JSON.stringify(measurement, null, 2), contentType: 'application/json' });
  console.log('LOCAL_PERFORMANCE', JSON.stringify(measurement));
  expect(measurement.sampleFrames).toBeGreaterThan(0);
});
